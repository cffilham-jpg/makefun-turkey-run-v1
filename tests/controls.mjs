import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || '/home/hatch/workspace/makefun/browser/node_modules/playwright-core/index.mjs');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/home/hatch/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:720},hasTouch:true});
const errors=[],requests=[];let loaded=false;
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
page.on('request',request=>{if(loaded)requests.push(request.url());});
await page.goto('http://127.0.0.1:8080/?seed=17');await page.waitForFunction(()=>window.gobble);
loaded=true;await page.context().setOffline(true);await page.clock.install();
await page.locator('#action').click();await page.clock.runFor(50);
assert.equal(await page.evaluate(()=>gobble.screen),'playing');
await page.locator('[data-control="duck"]').hover();await page.mouse.down();await page.clock.runFor(100);
assert.equal(await page.evaluate(()=>gobble.world.duck),true);await page.mouse.up();await page.clock.runFor(25);
await page.locator('[data-control="sprint"]').hover();await page.mouse.down();await page.clock.runFor(300);
assert.ok(await page.evaluate(()=>gobble.world.stamina<99));await page.mouse.up();
await page.locator('[data-control="jump"]').hover();await page.mouse.down();await page.clock.runFor(250);
assert.ok(await page.evaluate(()=>gobble.world.y < -50));await page.mouse.up();await page.clock.runFor(1100);
await page.mouse.move(600,350);await page.mouse.down();await page.clock.runFor(200);
assert.ok(await page.evaluate(()=>gobble.world.y< -50));await page.mouse.up();await page.clock.runFor(1200);
await page.locator('#pause').click();await page.clock.runFor(30);assert.equal(await page.evaluate(()=>gobble.screen),'paused');
await page.locator('#action').click();await page.clock.runFor(30);assert.equal(await page.evaluate(()=>gobble.screen),'playing');
const cdp=await page.context().newCDPSession(page);
const bounds=await page.locator('[data-control="duck"]').boundingBox();
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:bounds.x+bounds.width/2,y:bounds.y+bounds.height/2,id:0}]});await page.clock.runFor(100);
assert.equal(await page.evaluate(()=>gobble.world.duck),true,'touch hold ducks');
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.clock.runFor(30);
assert.equal(await page.evaluate(()=>gobble.world.duck),false,'touch release clears duck');
assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
console.log('PASS: offline mouse-only start, duck, sprint, button jump, canvas jump, pause/resume; real touch hold/release; zero errors and runtime requests.');
await browser.close();
